export type CompanyTier =
  | "FAANG+"
  | "Tier 1 Product"
  | "Indian Unicorn"
  | "Quant/Finance"
  | "Service Mass-Hirer"
  | "Global Enterprise"
  | "Consulting/Analytics";

export type RoundType = "OA" | "Tech" | "Group Discussion" | "Case" | "HR" | "Managerial" | "Bar Raiser";

export interface CompanyRound {
  type: RoundType;
  duration: string;       // e.g. "90 min", "45-60 min"
  format: string;         // e.g. "2 coding + 8 MCQ", "1 hard DSA + system design"
  platform?: string;      // HackerRank | Codility | TCS iON | etc.
  notes?: string;
}

export interface Company {
  id: number;
  slug: string;
  name: string;
  tier: CompanyTier;
  sector: string;          // "Cloud", "E-commerce", "Fintech", "IT Services"...
  hq: string;
  indianOffices: string[];
  websiteUrl: string;
  careersUrl?: string;
  logoLetter: string;      // single letter fallback (we render a neon tile)
  brandColor?: string;     // optional hex for visual diversity
  // hiring shape
  ctcBand: { min: number; typical: number; max: number; currency: "INR-LPA" | "USD" };
  locations: string[];
  rolesOffered: string[];  // "SDE-1", "Analyst", "Trader"...
  eligibility: {
    minCgpa?: number;
    minTenthPct?: number;
    minTwelfthPct?: number;
    allowedBranches: string[]; // ["CSE","IT","ECE","ALL"]
    backlogPolicy: "None" | "Active-none" | "Capped" | "Open";
  };
  hiringWindow: string;     // "Jul-Sep (final-year)", "Aug-Oct"...
  rounds: CompanyRound[];
  topicsAsked: {
    dsa: string[];
    coreCs: string[];
    systemDesign?: string[];
    behavioral?: string[];
  };
  oaTools: string[];        // platforms commonly used
  difficulty: 1 | 2 | 3 | 4 | 5; // 5 = brutal
  tipsFromOffers: string[]; // crisp 1-liners
  related: string[];        // slugs of similar companies
  verified: boolean;        // crowd-verified later
  lastUpdated: string;
}

