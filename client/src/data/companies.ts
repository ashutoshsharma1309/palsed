export const COMPANY_TIERS: CompanyTier[] = [
  "FAANG+","Tier 1 Product","Indian Unicorn","Quant/Finance","Service Mass-Hirer","Global Enterprise","Consulting/Analytics",
];

export function getCompany(slug: string): Company | undefined {
  return COMPANIES.find((c) => c.slug === slug);
}

export function searchCompanies(q: string): Company[] {
  const qq = q.trim().toLowerCase();
  if (!qq) return COMPANIES;
  return COMPANIES.filter((c) =>
    [c.name, c.tier, c.sector, c.indianOffices.join(" "), c.locations.join(" "), c.rolesOffered.join(" ")]
      .join(" ").toLowerCase().includes(qq)
  );
}
